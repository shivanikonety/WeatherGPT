const I18n = {
  languages: LANGUAGES,

  normalizeLang(lang) {
    if (!lang) return "en-IN";
    const l = lang.trim();
    if (LANGUAGES[l]) return l;
    const lower = l.toLowerCase();
    for (const code in LANGUAGES) {
      if (code.toLowerCase() === lower || code.toLowerCase().startsWith(lower)) {
        return code;
      }
    }
    if (lower === "hi") return "hi-IN";
    if (lower === "bn") return "bn-IN";
    if (lower === "mr") return "mr-IN";
    if (lower === "te") return "te-IN";
    if (lower === "ta") return "ta-IN";
    if (lower === "gu") return "gu-IN";
    if (lower === "ur") return "ur-IN";
    if (lower === "kn") return "kn-IN";
    if (lower === "or") return "or-IN";
    if (lower === "ml") return "ml-IN";
    if (lower === "en") return "en-IN";
    return "en-IN";
  },

  t(key, lang) {
    const norm = this.normalizeLang(lang);
    const dict = TRANSLATIONS[norm] || TRANSLATIONS["en-IN"];
    if (dict && dict[key] !== undefined) {
      return dict[key];
    }
    return TRANSLATIONS["en-IN"][key] || key;
  },

  getWeatherDescription(code, lang) {
    const norm = this.normalizeLang(lang);
    const names = WEATHER_CODE_NAMES[norm] || WEATHER_CODE_NAMES["en-IN"];
    return names[code] || WEATHER_CODE_NAMES["en-IN"][code] || "Clear";
  },

  formatNumber(num, lang) {
    try {
      const norm = this.normalizeLang(lang);
      return new Intl.NumberFormat(norm).format(num);
    } catch (e) {
      return num.toString();
    }
  },

  formatDate(date, lang, options) {
    try {
      const norm = this.normalizeLang(lang);
      return new Intl.DateTimeFormat(norm, options || { weekday: "long", month: "short", day: "numeric", hour: "2-digit", minute: "2-digit" }).format(date);
    } catch (e) {
      return date.toLocaleDateString();
    }
  },

  applyDirection(lang) {
    const norm = this.normalizeLang(lang);
    const config = LANGUAGES[norm] || LANGUAGES["en-IN"];
    document.documentElement.setAttribute("dir", config.direction);
    document.documentElement.setAttribute("lang", config.speechSynthesis);
  },

  setLanguage(lang) {
    const norm = this.normalizeLang(lang);
    this.currentLang = norm;
    this.applyDirection(norm);
    return norm;
  },

  getDirection(lang) {
    const norm = this.normalizeLang(lang);
    const config = LANGUAGES[norm] || LANGUAGES["en-IN"];
    return config.direction || "ltr";
  },

  getWmoDescription(code, lang) {
    return this.getWeatherDescription(code, lang);
  }
};

// Expose language registry on I18n object
I18n.LANGUAGES = LANGUAGES;
I18n.languages = LANGUAGES;

// Export to window for global access
if (typeof window !== "undefined") {
  window.LANGUAGES = LANGUAGES;
  window.TRANSLATIONS = TRANSLATIONS;
  window.WEATHER_CODE_NAMES = WEATHER_CODE_NAMES;
  window.I18n = I18n;
}

